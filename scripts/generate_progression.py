"""Generate the immutable stage catalogue from the shared JSON (no dependencies)."""
import json,pathlib
root=pathlib.Path(__file__).resolve().parents[1]
kotlin=(root/'app/src/main/assets/progression/stages.json').exists()
source=root/('app/src/main/assets/progression/stages.json' if kotlin else 'assets/progression/stages.json')
stages=json.loads(source.read_text())['stages']
assert len(stages)>20 and all(s['index']==i and s['id']==f'paco-{i+1:03}' for i,s in enumerate(stages))
assert all(19<=s['moves']<=24 and 60<=s['seconds']<=90 and s['target']>0 for s in stages)
assert all(s['legacy'] or (len(s['options'])>=2 and 0<=s['answer']<len(s['options'])) for s in stages)
def quote(text):
 value=json.dumps(text,ensure_ascii=False)
 return value.replace('$','\\$')
if kotlin:
 text='// Generated by scripts/generate_progression.py; edit the JSON catalogue.\npackage ci.paco.bourse.domain\n\n'
 text+='data class StageSpec(val id:String,val target:Int,val moves:Int,val seconds:Int,val topic:String,val question:String,val options:List<String>,val answer:Int,val explanation:String)\n'
 text+=f'const val TOTAL_STAGES = {len(stages)}\nval stageSpecs = listOf(\n'
 for s in stages:
  text+='    StageSpec('+','.join([quote(s['id']),str(s['target']),str(s['moves']),str(s['seconds']),quote(s['topic']),quote(s['question']),'listOf('+','.join(map(quote,s['options']))+')',str(s['answer']),quote(s['explanation'])])+'),\n'
 text+=')\n';target=root/'app/src/main/java/ci/paco/bourse/domain/StageCatalog.kt'
else:
 text='// Generated by scripts/generate_progression.py; edit the JSON catalogue.\n'
 text+='class StageSpec {\n const StageSpec(this.id,this.target,this.moves,this.seconds,this.topic,this.question,this.options,this.answer,this.explanation);\n final String id,topic,question,explanation;\n final int target,moves,seconds,answer;\n final List<String> options;\n}\n'
 text+=f'const stageCount = {len(stages)};\nconst stageSpecs = <StageSpec>[\n'
 for s in stages:
  text+=' StageSpec('+','.join([quote(s['id']),str(s['target']),str(s['moves']),str(s['seconds']),quote(s['topic']),quote(s['question']),'['+','.join(map(quote,s['options']))+']',str(s['answer']),quote(s['explanation'])])+'),\n'
 text+='];\n';target=root/'lib/domain/stage_catalog.dart'
target.write_text(text)
print(f'{len(stages)} stages: {target.relative_to(root)}')
